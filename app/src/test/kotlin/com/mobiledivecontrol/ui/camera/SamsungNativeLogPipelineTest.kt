package com.mobiledivecontrol.ui.camera

import org.junit.jupiter.api.Assertions.assertThrows
import org.junit.jupiter.api.Test

class SamsungNativeLogPipelineTest {
    @Test fun acceptsNativeColorMetadataAndRejectsPreviousTransferMismatch() {
        SamsungNativeLogPipeline.requireNativeColorMetadata(0, 2)
        for (transfer in listOf(null, 3, 6, 7)) {
            assertThrows(IllegalStateException::class.java) {
                SamsungNativeLogPipeline.requireNativeColorMetadata(transfer, 2)
            }
        }
        for (range in listOf(null, 0, 1)) {
            assertThrows(IllegalStateException::class.java) {
                SamsungNativeLogPipeline.requireNativeColorMetadata(0, range)
            }
        }
    }
    // SPS from SM-S921W native-recorder-key5.mp4, generated by our own UID probe.
    // Includes emulation prevention bytes and the actual Main10 profile/bit-depth fields.
    private val nativeSps = "00000001420101222000000300b0000003000003007ba003c0801107cad96bb9324ba9a848704817685094"
        .chunked(2).map { it.toInt(16).toByte() }.toByteArray()

    @Test fun acceptsObservedMain10Header() {
        SamsungNativeLogPipeline.requireMain10Sequence(nativeSps)
    }

    @Test fun acceptsThreeByteAnnexBStartCode() {
        SamsungNativeLogPipeline.requireMain10Sequence(nativeSps.drop(1).toByteArray())
    }

    @Test fun rejectsMainProfileEvenWhenBitDepthFieldsSayTen() {
        val wrongProfile = nativeSps.copyOf().also { it[7] = 0x21 }
        assertThrows(IllegalStateException::class.java) {
            SamsungNativeLogPipeline.requireMain10Sequence(wrongProfile)
        }
    }

    @Test fun rejectsMissingAndTruncatedHeaders() {
        assertThrows(IllegalStateException::class.java) {
            SamsungNativeLogPipeline.requireMain10Sequence(byteArrayOf(0, 0, 1, 0x40, 1, 0))
        }
        assertThrows(IllegalStateException::class.java) {
            SamsungNativeLogPipeline.requireMain10Sequence(nativeSps.copyOf(16))
        }
    }
}
